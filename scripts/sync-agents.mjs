#!/usr/bin/env node
// Generates OpenCode, Codex and Antigravity files from .claude/agents/*.md and .claude/skills.
// Source of truth: .claude/agents. Models: agents.models.json.
// Usage: node scripts/sync-agents.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, '.claude/agents');
const check = process.argv.includes('--check');
const models = JSON.parse(readFileSync(join(root, 'agents.models.json'), 'utf8'));
const MARK = 'Generated by scripts/sync-agents.mjs from .claude/agents. Do not edit.';

function parse(file) {
  const text = readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const fm = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i > 0) fm[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  for (const k of ['name', 'description']) if (!fm[k]) throw new Error(`${file}: missing ${k}`);
  return { fm, body: m[2].replace(/^\n+/, '') };
}

function pickModel(harness, name, alias) {
  const c = models[harness];
  const v = c.overrides?.[name] ?? c.aliases?.[alias] ?? c.default;
  if (v === undefined) throw new Error(`${harness}: no model for ${name} (alias "${alias}")`);
  return v; // null means inherit
}

const q = (s) => JSON.stringify(s);

// Claude tool list -> OpenCode permission block.
function opencodePermission(tools) {
  const t = new Set(tools);
  const allow = (...n) => (n.some((x) => t.has(x)) ? 'allow' : 'deny');
  return [
    'permission:',
    `  read: ${allow('Read')}`,
    `  glob: ${allow('Glob')}`,
    `  grep: ${allow('Grep')}`,
    `  edit: ${allow('Write', 'Edit')}`,
    `  bash: ${allow('Bash')}`,
    `  webfetch: ${allow('WebFetch')}`,
    `  websearch: ${allow('WebSearch')}`,
    '  task: deny',
  ].join('\n');
}

// Claude tool -> Antigravity tool names (spelled as on antigravity.google/docs/hooks). A wrong name can hang the subagent.
const AG_TOOLS = {
  Read: ['view_file', 'list_dir'], Glob: ['find_by_name'], Grep: ['grep_search'],
  Write: ['write_to_file'], Edit: ['replace_file_content', 'multi_replace_file_content'],
  Bash: ['run_command'], WebFetch: ['read_url_content'], WebSearch: ['search_web'],
};

const out = new Map();
for (const f of readdirSync(src).filter((f) => f.endsWith('.md')).sort()) {
  const { fm, body } = parse(join(src, f));
  // `tools: ToolSearch` alone means no working tools (Claude Code refuses an agent with zero tools, so a no-tools agent
  // names only ToolSearch, which loads nothing outside its list): every OpenCode permission denies, Antigravity gets an empty list
  const tools = (fm.tools ?? '').split(',').map((s) => s.trim()).filter((s) => s && s !== 'none' && s !== 'ToolSearch');

  const om = pickModel('opencode', fm.name, fm.model);
  out.set(`.opencode/agents/${fm.name}.md`, [
    '---',
    `description: ${q(fm.description)}`,
    'mode: subagent',
    ...(om ? [`model: ${om}`] : []),
    opencodePermission(tools),
    '---',
    `<!-- ${MARK} -->`,
    '',
    body,
  ].join('\n'));

  const am = pickModel('antigravity', fm.name, fm.model);
  const agTools = [...new Set(tools.flatMap((t) => { if (!AG_TOOLS[t]) throw new Error(`${f}: no Antigravity mapping for tool ${t}`); return AG_TOOLS[t]; }))];
  const policy = models.antigravity.commandExecutionPolicy;
  out.set(`.agents/agents/${fm.name}.md`, [
    '---',
    `name: ${fm.name}`,
    `description: ${q(fm.description)}`,
    'tools:',
    ...agTools.map((t) => `  - ${t}`),
    'subagent: true',
    'mainAgent: false',
    `model: ${am}`,
    ...(tools.includes('Bash') && policy ? [`commandExecutionPolicy: ${policy}`] : []),
    '---',
    `<!-- ${MARK} -->`,
    '',
    body,
  ].join('\n'));

  const cm = pickModel('codex', fm.name, fm.model);
  if (body.includes("'''")) throw new Error(`${f}: body contains '''`);
  out.set(`.codex/agents/${fm.name}.toml`, [
    `# ${MARK}`,
    `name = ${q(fm.name)}`,
    `description = ${q(fm.description)}`,
    ...(cm ? [`model = ${q(cm)}`] : []),
    `developer_instructions = '''`,
    body.trimEnd(),
    `'''`,
    '',
  ].join('\n'));
}

// Skills: .claude/skills/<name>/** -> .agents/skills/<name>/** (Antigravity; harmless for tools that also read .agents/skills).
const skillsSrc = join(root, '.claude/skills');
function walk(dir) {
  return readdirSync(dir).flatMap((n) => { const p = join(dir, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
}
if (existsSync(skillsSrc)) for (const file of walk(skillsSrc)) {
  const rel = file.slice(skillsSrc.length + 1);
  let data = readFileSync(file);
  if (file.endsWith('.md')) {
    const t = data.toString('utf8');
    const m = t.match(/^(---\n[\s\S]*?\n---\n)([\s\S]*)$/);
    data = Buffer.from(m ? `${m[1]}<!-- ${MARK} -->\n${m[2]}` : t);
  }
  out.set(`.agents/skills/${rel}`, data);
}

let stale = 0;
for (const [rel, content] of out) {
  const p = join(root, rel);
  const cur = existsSync(p) ? readFileSync(p) : null;
  if (cur && cur.equals(Buffer.from(content))) continue;
  stale++;
  if (check) { console.error(`stale: ${rel}`); continue; }
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, content);
  console.log(`wrote ${rel}`);
}
// Remove generated files whose source agent is gone.
for (const dir of ['.opencode/agents', '.codex/agents', '.agents/agents']) {
  const d = join(root, dir);
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d)) {
    const rel = `${dir}/${f}`;
    if (out.has(rel) || !readFileSync(join(d, f), 'utf8').includes(MARK)) continue;
    stale++;
    if (check) console.error(`orphan: ${rel}`); else { rmSync(join(d, f)); console.log(`removed ${rel}`); }
  }
}
if (check && stale) { console.error(`${stale} file(s) out of date. Run: node scripts/sync-agents.mjs`); process.exit(1); }
if (!stale) console.log('up to date');
