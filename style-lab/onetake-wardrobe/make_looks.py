#!/usr/bin/env python3
"""make_looks.py - bundle ALL six onetake looks into one looks.js (colours + subset OFL faces, one prefix per look),
so a single composition can restyle itself by token name. Uses onetake's own look.py (build_faces / comp_chars).
usage: python3 make_looks.py <onetake checkout> comp.html"""
import sys, json, pathlib, importlib.util, base64
ot = pathlib.Path(sys.argv[1]).resolve(); comp = pathlib.Path(sys.argv[2])
spec = importlib.util.spec_from_file_location("look", ot / "scripts" / "look.py"); L = importlib.util.module_from_spec(spec); spec.loader.exec_module(L)
db = L.load_db(); used, chars = L.comp_chars([comp])
out, faces_all, missing_all = {}, [], {}
for name, look in db["looks"].items():
    look = dict(look, name=name)
    faces, types, missing = L.build_faces(look, db, sorted(chars), None, prefix=name + "_")
    faces_all += faces
    out[name] = {"color": {k: look["color"][k] for k in L.COLORS}, "type": types, "mood": look["mood"], "from": look.get("from", "")}
    for f, m in missing.items(): missing_all.setdefault(f, set()).update(c for c in m if c in used)
js = "/* looks.js - generated by make_looks.py from onetake looks/looks.json (all six looks, OFL faces subset + inlined) */\n(function(root){\n'use strict';\n"
js += "const LOOKS = " + json.dumps(out, ensure_ascii=False) + ";\nconst FACES = [\n" + ",\n".join(f"  [{json.dumps(f)}, {json.dumps(w)}, '{b}']" for f, w, b in faces_all) + "\n];\n"
js += "const bytes = b64 => Uint8Array.from(atob(b64), c => c.charCodeAt(0));\n"
js += "LOOKS.ready = Promise.all(FACES.map(([family, weight, b64]) => { const f = new FontFace(family, bytes(b64), { weight }); root.document.fonts.add(f); return f.load(); }));\n"
js += "root.LOOKS = LOOKS;\n})(window);\n"
pathlib.Path("looks.js").write_text(js)
print("looks.js", round(len(js)/1024), "KB;", len(faces_all), "faces;", len(chars), "chars")
for f, m in missing_all.items():
    if m: print("  ! missing in", f, "".join(sorted(m)))
